const WORD_CATEGORIES = {};
const WORD_BANK = [];
(function build() {
  const norm = ch => (ch === 'إ' || ch === 'آ' || ch === 'ا') ? 'أ' : ch;
  for (const [key, [name, icon, list]] of Object.entries(WORD_BANK_RAW)) {
    WORD_CATEGORIES[key] = { name, icon };
    const seen = new Set();
    list.trim().split(/\s+/).forEach(tok => {
      const m = tok.match(/^([\u0600-\u06FF\-]+)(.*)$/);
      if (!m) return;
      const w = m[1].replace(/-/g, ' ');
      if (seen.has(w)) return; seen.add(w);
      WORD_BANK.push({ w, e: m[2] || '⭐', c: key, l: norm(w[0]) });
    });
  }
})();
