// جلب رابط تسجيل النشيد (باللحن) من ويكيميديا
window.fetchAnthemAudio = async function (id) {
  const cacheKey = 'harfi_anthem_audio_' + id;
  const cached = localStorage.getItem(cacheKey);
  if (cached) return cached === 'none' ? null : cached;
  const article = (window.ANTHEM_ARTICLES || {})[id];
  if (!article) return null;
  try {
    const url = 'https://en.wikipedia.org/w/api.php?action=query&format=json&origin=*&prop=images&imlimit=60&titles=' + encodeURIComponent(article);
    const res = await fetch(url);
    const data = await res.json();
    const pages = Object.values(data.query.pages);
    const files = (pages[0].images || [])
      .map(i => i.title)
      .filter(t => /\.(ogg|oga|wav|mp3|flac)$/i.test(t));
    if (!files.length) { localStorage.setItem(cacheKey, 'none'); return null; }
    const preferred = files.find(f => /instrumental|band|orchestr/i.test(f)) || files[0];
    const src = 'https://commons.wikimedia.org/wiki/Special:FilePath/' + encodeURIComponent(preferred.replace(/^File:/, ''));
    localStorage.setItem(cacheKey, src);
    return src;
  } catch {
    return null;
  }
};
